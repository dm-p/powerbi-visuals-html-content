// Prestep run before `pbiviz package`/`start`/`test`. Writes the two git-ignored
// edition artifacts: the sanitizer backend selector and the active-edition
// handoff that pbiviz.mjs reads. Capabilities are committed files (capabilities.json
// / capabilities.webaccess.json); pbiviz.mjs selects the path, so nothing is
// generated for them here.
//
// Usage: node scripts/select-edition.mjs <edition> [channel]
//   edition: certified | standard | standalone   (default: certified)
//   channel: alpha | beta                        (optional; prerelease builds
//            get a channel-prefixed GUID, a displayName suffix and a channel
//            icon — see resolveEditionConfig in config/editions.mjs)
//   Channel builds must be followed by `npx pbiviz package` directly — `npm
//   run package` and `npm test` reset the selection to certified via their
//   pre-hooks.
import { readFileSync, writeFileSync } from 'node:fs';
import { execSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { resolveEditionConfig } from '../config/editions.mjs';

const edition = process.argv[2] ?? 'certified';
const channel = process.argv[3];

const base = JSON.parse(
    readFileSync(new URL('../pbiviz.json', import.meta.url), 'utf8')
);

// Channel builds stamp the 4th version segment with the HEAD commit date
// (UTC) and commit, e.g. `2.0.0.20260813#b044cfdc` — computed ONCE here and
// handed to pbiviz.mjs via active-edition.mjs so packaged metadata and the
// landing page can never drift. Format changes must stay in step with the
// stamp assertion in scripts/assert-channel-identity.mjs. The date comes
// from the commit, not the wall clock, so the stamp is a pure function of
// HEAD — rebuilds and same-release edition builds can never drift.
const buildStamp = () => {
    let hash;
    let ymd;
    try {
        const cwd = fileURLToPath(new URL('..', import.meta.url));
        const opts = { cwd, stdio: ['ignore', 'pipe', 'ignore'] };
        hash = execSync('git rev-parse --short=8 HEAD', opts)
            .toString()
            .trim();
        ymd = execSync(
            'git show -s --format=%cd --date=format-local:%Y%m%d HEAD',
            { ...opts, env: { ...process.env, TZ: 'UTC' } }
        )
            .toString()
            .trim();
    } catch {
        console.error(
            'Channel builds need git metadata for the version stamp — run from a git checkout with git on PATH.'
        );
        process.exit(1);
    }
    const xyz = base.visual.version.split('.').slice(0, 3).join('.');
    if (!/^\d+\.\d+\.\d+$/.test(xyz)) {
        console.error(
            `pbiviz.json visual.version '${base.visual.version}' is not x.y.z[.n] — cannot build a channel stamp.`
        );
        process.exit(1);
    }
    return `${xyz}.${ymd}#${hash}`;
};
const versionOverride = channel ? buildStamp() : undefined;

let resolved;
try {
    resolved = resolveEditionConfig(base, edition, channel, versionOverride);
} catch (err) {
    console.error(err.message);
    process.exit(1);
}

const MARK_FILE = {
    flagship: 'shield.svg',
    secure: 'shield-secure.svg',
    standalone: 'shield-standalone.svg'
};
const markFile = MARK_FILE[resolved.edition];
if (!markFile) {
    console.error(
        `No mark asset defined for edition '${resolved.edition}' (edition key: ${edition})`
    );
    process.exit(1);
}

const backend = resolved.sanitize ? 'backend.certified' : 'backend.passthrough';
writeFileSync(
    new URL('../src/sanitize/backend.ts', import.meta.url),
    `// GENERATED by scripts/select-edition.mjs — do not edit.\n` +
        `export * from './${backend}';\n`
);

writeFileSync(
    new URL('../config/active-edition.mjs', import.meta.url),
    `// GENERATED by scripts/select-edition.mjs — do not edit.\n` +
        `export default '${edition}';\n` +
        `export const channel = ${channel ? `'${channel}'` : 'undefined'};\n` +
        `export const versionOverride = ${
            versionOverride ? `'${versionOverride}'` : 'undefined'
        };\n`
);

writeFileSync(
    new URL('../src/visual-config.generated.ts', import.meta.url),
    `// GENERATED by scripts/select-edition.mjs — do not edit.\n` +
        `export type Edition = 'flagship' | 'secure' | 'standalone';\n` +
        `export const EDITION: Edition = '${resolved.edition}';\n` +
        `export const CHANNEL: 'alpha' | 'beta' | undefined = ${
            channel ? `'${channel}'` : 'undefined'
        };\n` +
        `export const RESOLVED_VISUAL = ${JSON.stringify(
            resolved.visual,
            null,
            4
        )} as const;\n`
);

writeFileSync(
    new URL('../src/landing/mark.generated.ts', import.meta.url),
    `// GENERATED by scripts/select-edition.mjs — do not edit.\n` +
        `import mark from '../../assets/${markFile}';\n` +
        `export const MARK_URL: string = mark;\n`
);

console.log(
    `Selected edition: ${edition}${channel ? ` (${channel} channel, version ${resolved.visual.version})` : ''} (sanitize=${resolved.sanitize}, backend=${backend})`
);
